export function getPricingTerritory(countryCode: string | null | undefined): PricingTerritory | undefined {
  if (!countryCode) return undefined
  const c = String(countryCode).trim().toUpperCase()
  if (c.length !== 2) return undefined
  return COUNTRY_TO_PRICING_TERRITORY[c]
}
